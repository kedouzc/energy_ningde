def _battery_capex_yi(gwh, price_rmb_kwh):
    """GWh×元/kWh → 亿元。"""
    return gwh * price_rmb_kwh / 100.0


def _yearly_electrified_by_type(inc=None):
    """返回2026—2030逐车型电动化车辆（万），保持与expand_vehicles同一根参数。"""
    import copy
    P = inc or CONFIG_INC
    V = copy.deepcopy(P["vehicles"])
    dm = derive_operating_demand(P)
    for vt, vd in V.items():
        if vd.get("from_demand"):
            vd["stock"] = dm[vt]
        pe = vd.get("pure_elec", 1.0)
        if "sales" in vd:
            yearly = [x * pe for x in vd["sales"]]
        elif "fixed" in vd:
            yearly = [vd["fixed"] * pe / 5.0] * 5
        else:
            annual = vd["stock"] / vd["cycle"]
            yearly = [annual * n * pe for n in vd["nev"]]
        vd["yearly_ev_wan"] = yearly
    return V


def build_annual_swap_cohorts(inc=None, cfg=None):
    """逐年生成宁德换电车辆与装车GWh批次；这是初装和3.8年更新现金表的共同地基。"""
    P = inc or CONFIG_INC
    C = cfg or CONFIG_BUILD_PHASE
    V = _yearly_electrified_by_type(P)
    rows = {y: {} for y in C["年份"]}
    for vt, vd in V.items():
        kwh = vd["kwh"]
        for idx, year in enumerate(C["年份"]):
            veh = 0.0
            for sc in vd["scenes"]:
                veh += (vd["yearly_ev_wan"][idx] * sc.get("weight", 1.0)
                        * sc["swap_rate"] * sc["catl_swap"])
            rows[year][vt] = {
                "车辆_万": veh,
                "装车GWh": veh * 10000.0 * kwh / 1e6,
                "单车kWh": kwh,
            }
    return rows


def build_station_capex_schedule(cfg=None):
    """按2028网络建成目标计算逐年新增站体与站内周转电池。"""
    C = cfg or CONFIG_BUILD_PHASE
    rows = {}
    previous = {"重卡": 0, "巧克力": 0}
    for year in C["年份"]:
        share = C["累计建站比例"][year]
        row = {"累计比例": share, "新增站": {}, "累计站": {}, "新增站内GWh": 0.0,
               "站体原始CAPEX": 0.0, "站内电池原始CAPEX": 0.0}
        for stype in ("重卡", "巧克力"):
            cumulative = round(C["终局站数"][stype] * share)
            new = cumulative - previous[stype]
            blocks, block_kwh = C["单站周转电池"][stype]
            new_gwh = new * blocks * block_kwh / 1e6
            row["新增站"][stype] = new
            row["累计站"][stype] = cumulative
            row["新增站内GWh"] += new_gwh
            row["站体原始CAPEX"] += new * C["站体单价_万"][stype] / 1e4
            row["站内电池原始CAPEX"] += _battery_capex_yi(
                new_gwh, C["电池价格_元每kWh"][year]
            )
            previous[stype] = cumulative
        rows[year] = row
    return rows


def build_replacement_schedule(cohorts=None, inc=None, cfg=None):
    """3.8年寿命按均匀投放拆为y+3年20%、y+4年80%；因此首轮只落在2029—2030。"""
    P = inc or CONFIG_INC
    C = cfg or CONFIG_BUILD_PHASE
    cohorts = cohorts or build_annual_swap_cohorts(P, C)
    out = {y: {"更新GWh": 0.0, "更新毛CAPEX": 0.0, "旧电池残值回收": 0.0,
               "更新净CAPEX": 0.0, "来源": []} for y in C["年份"]}

    def life_of(vt):
        if vt in ("出租", "网约", "Robotaxi"):
            return P["swap_life"]["乘用营运"]
        return P["swap_life"].get(vt, 10.0)

    for cohort_year, typed in cohorts.items():
        for vt, data in typed.items():
            life = life_of(vt)
            if life > 4.0:
                continue
            # 均匀投放+3.8年寿命：20%落在y+3，80%落在y+4。
            for replacement_year, weight in ((cohort_year + 3, 0.20), (cohort_year + 4, 0.80)):
                if replacement_year not in out:
                    continue
                gwh = data["装车GWh"] * weight
                gross = _battery_capex_yi(gwh, C["电池价格_元每kWh"][replacement_year])
                salvage = _battery_capex_yi(gwh, C["电池价格_元每kWh"][cohort_year]) * C["短寿命残值率"]
                out[replacement_year]["更新GWh"] += gwh
                out[replacement_year]["更新毛CAPEX"] += gross
                out[replacement_year]["旧电池残值回收"] += salvage
                out[replacement_year]["更新净CAPEX"] += gross - salvage
                out[replacement_year]["来源"].append((cohort_year, vt, weight, gwh))
    return out


def _raw_ramp_ebitda(cumulative, station_row, cfg=None):
    """按当年在役车辆/站点正算爬坡期EBITDA，最终再校准至Part 3的806亿。"""
    C = cfg or CONFIG_BUILD_PHASE
    P = CONFIG_INC
    V = CONFIG_FWD
    days = P["days"]
    revenue = 0.0
    opex = 0.0
    for vt, data in cumulative.items():
        if vt == "重卡":
            freq, labor = P["freq"]["重卡"], V["人工运维_元每次"]["重卡"]
        elif vt == "城配物流":
            freq, labor = P["freq"]["城配物流"], V["人工运维_元每次"]["乘用"]
        elif vt == "私家车":
            freq, labor = P["freq"]["私家车"], V["人工运维_元每次"]["乘用"]
        else:
            freq, labor = P["freq"]["乘用营运"], V["人工运维_元每次"]["乘用"]
        veh = data["车辆_万"]
        kwh = data["单车kWh"]
        transaction_yi_kwh = veh * 1e4 * kwh * P["usable_factor"] * freq * days / 1e8
        revenue += transaction_yi_kwh * V["度电服务费_元"]
        revenue += data["装车GWh"] * 1e6 * V["度电租金_元每年"] / 1e8
        extra_charge = transaction_yi_kwh * ((1 + V["厂用电率"]) / V["RTE"] - 1)
        opex += extra_charge * V["谷电价_元每度"]
        opex += veh * 1e4 * freq * days * labor / 1e8

    station_gwh = 0.0
    for stype in ("重卡", "巧克力"):
        blocks, block_kwh = C["单站周转电池"][stype]
        station_gwh += station_row["累计站"][stype] * blocks * block_kwh / 1e6
    revenue += station_gwh * 0.60 * 1e6 * V["度电租金_元每年"] / 1e8
    revenue += station_gwh * 1e6 * V["套利天数"] * V["峰谷差_元每度"] * V["RTE"] / 1e8
    station_total = sum(station_row["累计站"].values())
    final_station_total = sum(C["终局站数"].values())
    station_share = station_total / final_station_total if final_station_total else 0.0
    revenue += CONFIG_INC["ancillary_yi"] * station_share
    opex += station_total * V["单站年租_万"] / 1e4
    opex += 5.0 + 15.0 * station_share  # 平台底座5亿+随网络扩展15亿，终局20亿。
    return revenue - opex


def build_build_phase_cashflow(inc=None, cfg=None):
    """2026—2030年度建设现金表：40%权益固定，初装按物理批次分年，更新按寿命批次发生。"""
    P = inc or CONFIG_INC
    C = cfg or CONFIG_BUILD_PHASE
    cohorts = build_annual_swap_cohorts(P, C)
    stations = build_station_capex_schedule(C)
    replacements = build_replacement_schedule(cohorts, P, C)

    raw_initial = {}
    for year in C["年份"]:
        vehicle_gwh = sum(x["装车GWh"] for x in cohorts[year].values())
        raw_initial[year] = {
            "车辆电池": _battery_capex_yi(vehicle_gwh, C["电池价格_元每kWh"][year]),
            "站内电池": stations[year]["站内电池原始CAPEX"],
            "站体": stations[year]["站体原始CAPEX"],
        }
    raw_total = sum(sum(x.values()) for x in raw_initial.values())
    calibration = C["初装CAPEX锚_亿"] / raw_total

    cumulative = {vt: {"车辆_万": 0.0, "装车GWh": 0.0, "单车kWh": data["单车kWh"]}
                  for vt, data in cohorts[C["年份"][0]].items()}
    raw_ebitda = {}
    cumulative_snapshot = {}
    for year in C["年份"]:
        for vt, data in cohorts[year].items():
            cumulative[vt]["车辆_万"] += data["车辆_万"]
            cumulative[vt]["装车GWh"] += data["装车GWh"]
        cumulative_snapshot[year] = {k: v.copy() for k, v in cumulative.items()}
        raw_ebitda[year] = _raw_ramp_ebitda(cumulative, stations[year], C)
    # 正算细项的未取整/站数差异统一校准回Part 3披露的806亿终局EBITDA。
    ebitda_scale = 806.0 / raw_ebitda[2030]

