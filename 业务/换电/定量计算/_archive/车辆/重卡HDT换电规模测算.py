# ============================================================
# 计算逻辑（无需修改，复刻 Excel 公式）
# ============================================================

def compute(cfg: dict):
    R = {}

    # ============================================================
    # 存量部分（2025 年已售车辆）
    #   HDT NEV 存量车辆数 = 2025 HDT NEV销量 × 换电渗透率 × CATL市占率   【Excel D7】
    #   存量换电装机规模   = 单车带电量 × HDT NEV 存量车辆数             【Excel D5】
    # ============================================================
    # 单车带电量(kWh) 【Excel D6】来自 CONFIG
    # 2025 HDT NEV销量 / 换电渗透率 / CATL市占率 【Excel D8/D9/D10】来自 CONFIG
    hdt_nev_stock_vehicles = round(                      # 存量车辆数(万辆)，对应 Excel D7
        cfg["存量_2025_HDT_NEV销量_万辆"]
        * cfg["存量_换电渗透率"]
        * cfg["存量_CATL市占率"], 1)
    stock_capacity = (                                  # 存量换电装机规模(万kWh)，对应 Excel D5
        cfg["存量_单车带电量_kWh"] * hdt_nev_stock_vehicles)

    # ============================================================
    # 增量部分（2026–2030 新车）
    #   HDT NEV 增量车辆数 = 新能源重卡总销量 × 换电渗透率 × CATL市占率   【Excel D13】
    #   增量换电装机规模   = 单车带电量 × HDT NEV 增量车辆数             【Excel D11】
    # ============================================================
    # 增量阶段单车带电量(kWh) 【Excel D12】来自 CONFIG

    # 重卡总销量(2026-2030) = 平均年销量 × 5年          【Excel D15】
    # 平均年销量 = 保有量 ÷ 更新周期                     【Excel D16】
    avg_annual_sales = (                               # 平均年销量(万辆)，对应 Excel D16
        cfg["重卡_2030保有量_万辆"] / cfg["重卡_更新周期_年"])
    total_truck_sales = avg_annual_sales * cfg["测算年限_年"]  # 重卡总销量(万辆)，对应 Excel D15

    # NEV 平均渗透率(2026–2030) 【Excel D19 = AVERAGE(D21:D25)】
    # 注意：2025(0.28) 是基准年，不计入均值；2025→2030 为 S 型增长曲线
    nev_rates = [cfg[f"NEV渗透率_{y}"] for y in ("2026", "2027", "2028", "2029", "2030")]
    nev_avg_rate = sum(nev_rates) / len(nev_rates)

    # 新能源重卡总销量(2026–2030) = 重卡总销量 × NEV平均渗透率   【Excel D14】
    nev_truck_sales = total_truck_sales * nev_avg_rate   # 万辆

    # 增量阶段换电渗透率【Excel D26】& CATL市占率【Excel D27】：
    #   由 a/b/c 里程场景按销量权重加权得到（权重来自 JP Morgan 续航里程销量统计）
    sw = sum(s["weight"] for s in cfg["场景"])
    swap_rate_weighted = sum(s["weight"] * s["swap_rate"] for s in cfg["场景"]) / sw
    catl_share_weighted = sum(s["weight"] * s["catl_share"] for s in cfg["场景"]) / sw

    # 增量车辆数(万辆) = ROUND(新能源重卡总销量 × 换电渗透率 × CATL市占率, 0)   【Excel D13】
    hdt_nev_increment_vehicles = round(nev_truck_sales * swap_rate_weighted * catl_share_weighted, 0)
    increment_capacity = cfg["增量_单车带电量_kWh"] * hdt_nev_increment_vehicles  # 万kWh，对应 Excel D11

    # ============================================================
    # 汇总
    #   总换电装机规模 = 存量换电规模 + 增量换电规模             【Excel D3】
    #   总换电车辆规模 = HDT NEV存量车辆数 + HDT NEV增量车辆数   【Excel D4】
    # ============================================================
    R["总换电装机规模_万kWh"] = stock_capacity + increment_capacity
    R["总换电车辆规模_万辆"] = hdt_nev_stock_vehicles + hdt_nev_increment_vehicles

    # 明细（供检查）
    R["_明细"] = {
        "存量_HDT_NEV存量车辆数_万辆": hdt_nev_stock_vehicles,
        "存量换电装机规模_万kWh": stock_capacity,
        "重卡平均年销量_万辆": avg_annual_sales,
        "重卡总销量_万辆": total_truck_sales,
        "NEV平均渗透率": nev_avg_rate,
        "新能源重卡总销量_万辆": nev_truck_sales,
        "增量_换电渗透率加权": swap_rate_weighted,
        "增量_CATL市占率加权": catl_share_weighted,
        "增量_HDT_NEV增量车辆数_万辆": hdt_nev_increment_vehicles,
        "增量换电装机规模_万kWh": increment_capacity,
    }
    return R


