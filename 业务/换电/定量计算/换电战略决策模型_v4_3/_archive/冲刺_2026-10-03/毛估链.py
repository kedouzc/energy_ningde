def station(t):
    eq = IN["设备_万元"]; other = IN["其余投资_万元"]; kw = IN["站千瓦"]
    dep = eq / IN["设备寿命_年"] + other / IN["其余寿命_年"]               # 万元/年
    opex = IN["场地_万元每年"] + IN["人员_万元每年"] + IN["维修比例"] * eq + IN["保险比例"] * (eq + other)
    return dict(站投资=eq + other, 折旧每千瓦=dep * 1e4 / kw, 运营每千瓦=opex * 1e4 / kw,
                固定每千瓦=(dep + opex) * 1e4 / kw)

def network(t):
    d = demand(t)
    per = IN["每站每天_度"] * IN["运营天数"] / 1e8            # 每站一年卖的电（亿度）
    trunk_d = d["接力需求"] + d["争夺块需求"]
    n_trunk = trunk_d / per
    n_short = d["多班倒需求"] / per
    return dict(d, 干线需求=trunk_d, 干线卖量=trunk_d, 接力卖量=d["接力需求"], 争夺块卖量=d["争夺块需求"],
                多班倒卖量=d["多班倒需求"], 合计卖量=trunk_d + d["多班倒需求"], 干线站数=n_trunk, 短途站数=n_short,
                宁德规划够几成=IN["宁德规划站数2030"] / n_trunk, 干线每千瓦每天=IN["设计每千瓦每天_度"])

