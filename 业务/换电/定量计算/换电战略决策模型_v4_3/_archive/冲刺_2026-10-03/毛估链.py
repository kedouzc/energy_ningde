def annuity(rate, years):
    return rate / (1 - (1 + rate) ** (-years))

def rival_uplift():
    """对手要 7.5% 回报时，限价每度能高多少（只作敏感性；0.4 第 13 条基准是对手收益率 0）"""
    w = IN["WACC"]
    capex = 865; eq = capex * 0.325; other = capex - eq                      # 普通快充每千瓦投资与设备占比（3.1 节）
    st = (eq * annuity(w, 10) + other * annuity(w, 20) - (eq / 10 + other / 20)) / (7.3 * 350)
    bat = {"接力": (0.107, 3.74), "多班倒": (0.112, 12), "争夺块": (0.112, 10)}
    return {k: st + b * (annuity(w, L) * L - 1) for k, (b, L) in bat.items()}, st

def valuation(t):
    e = economics(t)
    ev18 = IN["倍数"] * e["EBITDA"]
    ev18adj = IN["倍数"] * (e["EBITDA"] - e["电池更新"])
    dcf = e["EBIT"] * (1 - IN["所得税"]) / IN["WACC"]
    up, _ = rival_uplift()
    vol = {"接力": e["接力卖量"], "争夺块": e["争夺块卖量"], "多班倒": e["多班倒卖量"]}
    ebit_r = e["EBIT"] + sum(vol[k] * up[k] for k in vol)
    dcf_r = ebit_r * (1 - IN["所得税"]) / IN["WACC"]
    return dict(e, 电池折旧占EBITDA=e["电池更新"] / e["EBITDA"], 倍数法=ev18, 倍数法扣电池更新=ev18adj, 现金流法=dcf, 现金流法减投资=dcf - e["投资合计"],
                对手要回报时EBIT=ebit_r, 对手要回报时现金流法=dcf_r)

