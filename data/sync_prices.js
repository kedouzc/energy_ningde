// -------- 注入 constants.js --------
// 策略：清除所有历史 AUTO-GEN 块 + v1.0 残留常量 + 旧"五、电池价格体系"段，
//       再在"六、备电租赁"段前插入干净 AUTO-GEN 区，确保单一价格真源、无旧函数覆盖。
function syncConstants() {
  let src = fs.readFileSync(CONST, 'utf8');
  const block = AUTO_OPEN + '\n' + genConstantsSection() + AUTO_CLOSE + '\n';

  // 1) 删除任何已有 AUTO-GEN 块（含首次误插的）
  const reAuto = new RegExp(AUTO_OPEN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + AUTO_CLOSE.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  src = src.replace(reAuto, '');

  // 2) 删除 v1.0 残留常量赋值（CELL_COST_DECLINE_RATE 等）
  src = src.replace(/Engine\.CELL_COST_DECLINE_RATE = [^\n]*\n/g, '');
  src = src.replace(/Engine\.ESS_CELL_COST_DECLINE_RATE = [^\n]*\n/g, '');
  src = src.replace(/Engine\.ESS_CELL_COST_Y0 = [^\n]*\n/g, '');

  // 3) 删除旧"五、电池价格体系"段（从段注释到 DEFAULT_GROSS_MARGIN 行），保留其后 SC_FEE
  const reSec5 = /\/\/ 五、电池价格体系（pack级[\s\S]*?Engine\.DEFAULT_GROSS_MARGIN = 22;\n/;
  if (reSec5.test(src)) src = src.replace(reSec5, '');

  // 4) 在"六、备电租赁价格体系"段前插入干净 AUTO-GEN 区
  const anchor = '// 六、备电租赁价格体系';
  const idx = src.indexOf(anchor);
  if (idx < 0) throw new Error('constants.js 未找到"六、备电租赁"锚点');
  src = src.slice(0, idx) + block + '\n' + src.slice(idx);

  fs.writeFileSync(CONST, src, 'utf8');
  console.log('[ok] constants.js AUTO-GEN 区已更新（旧五段/残留已清理）');
}

