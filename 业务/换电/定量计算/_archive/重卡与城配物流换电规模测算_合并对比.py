def validate_terminal_model():
    """两阶段终局关键勾稽：建设期40%固定、初装445对账、更新时点与成熟后出售时点正确。"""
    build = build_build_phase_cashflow()
    assert all(abs(r["建设期CATL权益"] - 0.40) < 1e-12 for r in build["年度"]), "2030前权益必须固定40%"
    assert abs(build["初装CAPEX合计"] - 2782.0) < 1e-6, "年度初装必须勾稽2,782亿"
    assert abs(build["CATL初装资本合计"] - 445.12) < 1e-6, "CATL初装资本必须勾稽445亿"
    assert abs(sum(r["新增车辆电池GWh"] for r in build["年度"]) - 385.0) < 0.2, "逐年装车批次应勾稽约385GWh"
    assert sum(r["新增站_重卡"] for r in build["年度"]) == NETWORK_STATION_TARGETS["重卡"]
    assert sum(r["新增站_巧克力"] for r in build["年度"]) == NETWORK_STATION_TARGETS["巧克力"]
    assert build["CATL单年峰值"] < 200.0, "基准情景单年资本峰值不应超过200亿"
    assert all(r["更新净CAPEX"] == 0 for r in build["年度"] if r["年份"] < 2029), "首轮更新不得早于2029"
    assert all(r["更新净CAPEX"] > 0 for r in build["年度"] if r["年份"] in (2029, 2030)), "3.8年批次应在2029—2030出现"
    for exit_year in CONFIG_MATURE_EXIT["退出年份情景"]:
        d = build_post_stable_exit_table(exit_year, build)
        assert exit_year >= CONFIG_MATURE_EXIT["最早出表年"]
        assert abs(d["40%换电价值支撑"] - 6792.0) < 1e-6
        assert all(s["业务数据控制权"] for s in d["场景"])
        s40 = next(s for s in d["场景"] if abs(s["终局权益"] - 0.40) < 1e-12)
        assert abs(s40["一次性出售回款"]) < 1e-12
    try:
        build_post_stable_exit_table(CONFIG_MATURE_EXIT["最早出表年"] - 1, build)
    except ValueError:
        pass
    else:
        raise AssertionError("稳定经营门槛前不得生成出表情景")
    return True


