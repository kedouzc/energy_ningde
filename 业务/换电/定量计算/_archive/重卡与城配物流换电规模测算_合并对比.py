def build_total_table(r_hdt, r_city, r_taxi, r_private):
    """组装总表：重卡 / 城配 / 乘用营运 / 私家车(三档)。返回各段 dict + 三档合计。
    私家车单站标准与乘用营运同（巧克力站 200万/座，用户2026-08-20修正）。
    """
    V = CONFIG_VAL

    # —— 各段输入（车辆数统一为增量模型口径，保证站数反推与增量四层一致）——
    _sw = catl_swap_veh_wan()   # 各车型宁德换电车辆(万)
    重卡车辆 = _sw["重卡"]                                       # ~38万
    重卡单车 = CONFIG_HDT["增量_单车带电量_kWh"]                # 500
    城配车辆 = _sw["城配物流"]                                   # ~32万（全电动口径下换电宁德车辆）
    城配单车 = CONFIG_CITY["单车带电量_kWh"]                    # 80
    乘用车辆 = _sw["出租"] + _sw["网约"] + _sw["Robotaxi"]      # ~88万
    乘用单车 = CONFIG_TAXI["背电_kWh"]                          # 56

    # —— 站数：统一为增量模型反推口径（物理容量要求，非官方规划锚）——
    # 重卡站数 = ceil(重卡需求 / 192)；巧克力站数 = ceil((城配+乘用营运+私家车)×f / 300)
    # 私家车仍不单独建站，其需求已计入巧克力反推站数（建足够多的巧克力站覆盖全部需求）。
    # 与 CATL_换电增量估值模型_v2.0.py 同源：stations = ceil(demand / design_capacity)
    重卡f = CONFIG_INC["freq"]["重卡"]                       # 1.8
    重卡站数 = NETWORK_STATION_TARGETS["重卡"]                  # 192次/天反推后的主报告稳健目标
    城配f = CONFIG_INC["freq"]["城配物流"]                     # 1.3
    乘用f = CONFIG_INC["freq"]["乘用营运"]                     # 1.42
    私家f = CONFIG_INC["freq"]["私家车"]                       # 0.2
    网络车辆 = 重卡车辆 + 城配车辆 + 乘用车辆
    # 重卡需求（万次/天）
    重卡需求_万次 = 重卡车辆 * 重卡f
    # 巧克力需求（万次/天）= 城配 + 乘用营运 + 私家车(各档)
    私家车需求_万次 = {sc: FWD_SEG["私家"+sc]["车"] * 私家f
                      for sc in ("保守", "稳健", "激进")}
    总换电次数_万每天 = 重卡需求_万次 + 城配车辆 * 城配f + 乘用车辆 * 乘用f + 私家车需求_万次["稳健"]
    城配站数 = 0                                            # 共用巧克力站，不单独建
    def _choco_stations(私家车辆):
        d = 城配车辆 * 城配f + 乘用车辆 * 乘用f + 私家车辆 * 私家f
        return math.ceil(d * 1e4 / V["单站能力_次每天"])
    乘用站数 = {sc: _choco_stations(FWD_SEG["私家"+sc]["车"]) for sc in ("保守", "稳健", "激进")}
    乘用站数["稳健"] = NETWORK_STATION_TARGETS["巧克力"]

    # 寿命：重卡按加权 f 反推（5.7年），乘用/城配按站点级 f≈1.4 反推（3.8年）
    V["_寿命覆盖"] = None
    重卡seg = compute_segment_val(重卡车辆, 重卡单车, 重卡站数, V["重卡_单站块数"], V["重卡_单块kWh"],
                                 V["重卡_EAC倍数"], V["重卡_单站投资额_万"], V)
    城配seg = compute_segment_val(城配车辆, 城配单车, 城配站数, 0, 0,
                                 V["其他_EAC倍数"], 0, V)
    # 乘用寿命用站点级 f 反推：循环(约3500)÷频次(1.4)÷350 ≈ 3.8；compute_segment_val 内部默认3.8
    # 乘用seg 按情景档（站数随私家车并入档位不同）
    乘用seg = {sc: compute_segment_val(乘用车辆, 乘用单车, 乘用站数[sc],
                                       V["乘用_单站块数"], V["乘用_单块kWh"],
                                       V["其他_EAC倍数"], V["乘用_单站投资额_万"], V)
              for sc in ("保守", "稳健", "激进")}

    # —— 私家车三档（2026-08-23 起不再新建站、并入营运站，站数/站内GWh=0，仅保留装车电池收益）——
    私家车段 = {}
    for sc in ("保守", "稳健", "激进"):
        fk = "私家" + sc
        veh = FWD_SEG[fk]["车"]
        站数 = FWD_SEG[fk]["站"]          # 已为0（并入）
        seg = compute_segment_val(veh, CONFIG_PRIVATE["单车带电量_kWh"], 站数,
                                  V["乘用_单站块数"], V["乘用_单块kWh"],
                                  V["私家车_EAC倍数"], V["私家车_单站投资额_万"], V)
        私家车段[sc] = seg

    # —— 三档合计（重卡 + 城配 + 乘用营运(对应档站数) + 私家车对应档）——
    def _merge(sc):
        base = [重卡seg, 城配seg, 乘用seg[sc], 私家车段[sc]]
        def _s(key):
            return round(sum(s[key] for s in base), 1)
        return {
            "车辆_万": sum(s["车辆_万"] for s in base),
            "装车GWh": _s("装车GWh"), "站内GWh": _s("站内GWh"), "总装机GWh": _s("总装机GWh"),
            "初装电池CAPEX": _s("初装电池CAPEX"), "站体CAPEX": _s("站体CAPEX"), "初装合计": _s("初装合计"),
            "全周期": _s("全周期"), "期末残值": _s("期末残值"), "折旧基础": _s("折旧基础"),
            "折旧基础总额": _s("折旧基础总额"), "年折旧": _s("年折旧"),
            "fcff": _s("fcff"), "ebitda": _s("ebitda"), "ev": _s("ev"),
            "债务": _s("债务"), "股权": _s("股权"), "宁德贡献": _s("宁德贡献"),
            "宁德年可分": round(sum(s["宁德年可分"] for s in base), 1),
            "宁德股权出资": round(sum(s["宁德股权出资"] for s in base), 1),
            "股权年可分配": round(sum(s["股权年可分配"] for s in base), 1),
            "宁德股权全投资": round(sum(s["宁德股权全投资"] for s in base), 1),
            "对外股权融资": round(sum(s["对外股权融资"] for s in base), 1),
            "对外融资总额": round(sum(s["对外融资总额"] for s in base), 1),
        }
    合计 = {sc: _merge(sc) for sc in ("保守", "稳健", "激进")}

    return {"重卡": 重卡seg, "城配": 城配seg, "乘用": 乘用seg, "私家车": 私家车段,
            "合计": 合计, "乘用站数": 乘用站数, "网络车辆": 网络车辆,
            "总换电次数_万每天": round(总换电次数_万每天, 1), "私家车_raw": r_private}


