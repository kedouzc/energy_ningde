  const WACC = 0.075;
  const powWACC = function (y) { return Math.pow(1 - WACC, y); };
  function row(years) {
    const buyNew = P.discountAt(D, years, 'power');   // ① 买新折
    const essDisc = P.discountAt(D, years, 'ess');    // ②a 储能降价折
    const capSec = 0.48;                              // ②b 容量二手折（不随价格变）
    const res = essDisc * capSec;                    // ② 残值折
    const net = buyNew - res;                        // ③ 净重置
    const disc = powWACC(years);                     // ④ WACC 贴现折
    const total = net * disc;                        // ⑤ 总折扣
    return { buyNew: buyNew, essDisc: essDisc, res: res, net: net, disc: disc, total: total };
  }
  const pct = function (x) { return (x * 100).toFixed(0) + '折'; };
  const p2 = function (x) { return x.toFixed(2); };

  // 重卡：役龄 5.7 / 11.4
  const r1 = row(5.7), r2 = row(11.4);
