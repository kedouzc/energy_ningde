def cont_margin(t):
    """争夺块里选换电的（换电便宜的有桩三格）每过站一度的利润，按过站电量加权"""
    zm, cm = IN["中途车数比"] * IN["中途年用电_万度"], IN["长途车数比"] * IN["长途年用电_万度"]
    w2 = IN["模式2占干线用电"] / (IN["模式2占干线用电"] + IN["模式3占干线用电"])
    m2l = w2 * cm / (zm + cm); m3 = 1 - w2                       # 占争夺块用电：只白天跑的长途、只夜里跑
    p2l = 448 / 910
    m3m = -(zm / (zm + cm) * cell_diff("模式3中途", t) + cm / (zm + cm) * cell_diff("模式3长途", t))
    a = m2l * p2l * (-cell_diff("模式2长途", t) / p2l) + m3 * m3m
    return a / (m2l * p2l + m3)

def margin_contested(t):
    cells = [cell_diff(k, t) for k in ["模式2中途", "模式2长途", "模式3中途", "模式3长途", "没桩中途", "没桩长途"]]
    avg = -sum(cells) / len(cells)
    return max(0.0, avg), avg

def relay_take(t):
    """接力车选换电 ＝ Σ 各年买的车在 2030 年接力用电里的占比 × 那年网铺到的比例 × 网铺到时选换电的比例"""
    life = IN["一辆重卡一生里程_万公里"] / IN["接力车每年里程_万公里"]      # 约 2.76 年
    years = [2030, 2029, 2028, 2027]
    w = {}
    left = life
    for y in years:
        f = min(1.0, max(0.0, left)); left -= 1
        if f > 0: w[y] = f * IN["干线新车_万辆"] * IN["干线电动化率"][y]
    tot = sum(w.values()); w = {y: v / tot for y, v in w.items()}
    path = IN["骐骥站数路径"][t]
    avail = {y: min(1.0, path[y] / IN["干线铺满站数"]) for y in w}
    a = sum(w[y] * avail[y] for y in w)
    return a * IN["接力选换电_网铺到时"][t], a, w, avail, life

def cont_avail(t):
    """有长停的干线车 9 年一换：2030 年路上是 2022—2030 年买的车；买车那年网铺到了才可能选换电"""
    rate = IN["干线电动化率"]; new = IN["干线新车_万辆"]
    w = {y: new * rate[y] for y in range(2025, 2031)}
    w[2024] = max(0.0, 180.1 - sum(w.values()))            # 2025 年以前买、2030 年还在跑的（第 2 章干线保有 180.1 万辆）
    path = IN["骐骥站数路径"][t]
    av = {y: (min(1.0, path[y] / IN["干线铺满站数"]) if y in path else 0.0) for y in w}
    tot = sum(w.values())
    return sum(w[y] * av[y] for y in w) / tot, w, av

def demand(t):
    relay_e = IN["干线用电_亿度"] * IN["接力占干线用电"]
    cont_e = IN["干线用电_亿度"] * (1 - IN["接力占干线用电"])
    multi_e = E_SHORT * IN["多班倒占短途"]
    take_r = relay_take(t)[0]
    d_relay = relay_e * IN["干线可及比例"] * take_r
    # 争夺块：悲观六格全贵，不选；中性、乐观：换电便宜的格全选，再乘按车龄加权的铺到比例
    d_cont = cont_e * IN["干线可及比例"] * IN["争夺块便宜格占比"][t] * cont_avail(t)[0] * IN["争夺块便宜格过站"]
    d_multi = multi_e * IN["多班倒选换电"][t]
    return dict(接力用电=relay_e, 争夺块用电=cont_e, 多班倒用电=multi_e,
                接力需求=d_relay, 争夺块需求=d_cont, 多班倒需求=d_multi)

