def catl(t):
    v = valuation(t)
    per_wh_np = IN["动力电池收入2025_亿元"] / IN["动力电池销量2025_GWh"] / 10 * IN["集团净利率2025"]  # 元/Wh
    rep_gwh = v["电池更新"] * 1e8 / IN["电池单价_元每度"] / 1e6                                    # 每年换电池 GWh
    pull_np = rep_gwh * IN["宁德多拿份额"][t] * per_wh_np * 10                                     # 亿元净利
    pull_mv = pull_np * IN["制造市盈率"]
    moat_np = IN["动力电池收入2025_亿元"] * IN["不做换电净利率少_点"][t] / 100
    moat_mv = moat_np * IN["制造市盈率"]
    mc = IN["宁德市值_亿元"]
    return dict(v, 每Wh净利=per_wh_np, 每年换电池GWh=rep_gwh, 多卖电池净利=pull_np, 多卖电池市值=pull_mv,
                护城河净利=moat_np, 护城河市值=moat_mv,
                合计_倍数法=v["倍数法"] + pull_mv + moat_mv,
                合计_复核=v["倍数法扣电池更新"] + pull_mv + moat_mv,
                合计_现金流=v["现金流法"] + pull_mv + moat_mv,
                净增值_倍数法=v["倍数法"] - v["投资合计"] + pull_mv + moat_mv,
                净增值_复核=v["倍数法扣电池更新"] - v["投资合计"] + pull_mv + moat_mv,
                净增值_现金流=v["现金流法"] - v["投资合计"] + pull_mv + moat_mv,
                净增值_对手要回报=v["对手要回报时现金流法"] - v["投资合计"] + pull_mv + moat_mv,
                占市值_倍数法=(v["倍数法"] + pull_mv + moat_mv) / mc,
                占市值_复核=(v["倍数法扣电池更新"] + pull_mv + moat_mv) / mc,
                占市值_现金流=(v["现金流法"] + pull_mv + moat_mv) / mc,
                每点净利率市值=IN["动力电池收入2025_亿元"] / 100 * IN["制造市盈率"])

