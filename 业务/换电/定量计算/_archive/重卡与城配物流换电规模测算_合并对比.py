# CONFIG_TAXI 计算（出租 / 网约车 / Robotaxi 三层独立）
#   原则：f = 日均里程 ÷ 实际续航；续航 = 背电_kWh ÷ 电耗
#         与装机层「单车带电量」解耦；出租/网约拆两层（出租刚性139万锚、网约=残差）
# ============================================================

def compute_taxi(cfg: dict):
    """出租(刚性) / 网约车(残差) / Robotaxi：车辆数与换电频次，各层独立后站点级加权。"""
    years = cfg["测算年限_年"]
    e = cfg["电耗_kWh_per_km"]
    rng = cfg["背电_kWh"] * cfg["余电折扣"] / e    # 同电池同电耗 → 同可用性续航（打八折）
    nev_rates = [cfg[f"NEV渗透率_{y}"] for y in ("2026", "2027", "2028", "2029", "2030")]
    nev_avg = sum(nev_rates) / len(nev_rates)

    # —— 出租（刚性 139万保有量锚）——
    avg_出租 = cfg["出租_刚性保有_万辆"] / cfg["更新周期_年"]
    nev_出租 = avg_出租 * years * nev_avg
    inc_出租 = round(nev_出租 * cfg["出租_换电渗透率"] * cfg["出租_CATL市占率"], 0)
    f_出租 = cfg["出租_日均里程_km"] / rng          # 450÷299

    # —— 网约（残差 = 有人活跃车 − 出租）——
    net_网约 = cfg["有人_活跃营运车_万辆"] - cfg["出租_刚性保有_万辆"]
    avg_网约 = net_网约 / cfg["更新周期_年"]
    nev_网约 = avg_网约 * years * nev_avg
    inc_网约 = round(nev_网约 * cfg["网约_换电渗透率"] * cfg["网约_CATL市占率"], 0)
    f_网约 = cfg["网约_日均里程_km"] / rng          # 342÷299

    # —— Robotaxi ——
    inc_robot = round(cfg["Robotaxi_2030保有_万辆"] * cfg["Robotaxi_换电渗透率"] * cfg["Robotaxi_CATL市占率"], 0)
    f_robot = cfg["Robotaxi_日均里程_km"] / rng     # 450÷299

    # 站点级合并 f（按进宁德车辆加权：出租+网约+Robotaxi+城配需外部传入，此处仅乘用车三层）
    parts = [(inc_出租, f_出租), (inc_网约, f_网约), (inc_robot, f_robot)]
    tot = sum(v for v, _ in parts)
    f_taxi = sum(v * f for v, f in parts) / tot if tot else 0

    return {
        "出租_进宁德_万辆": inc_出租,
        "出租_f_次每天": round(f_出租, 1),
        "网约_进宁德_万辆": inc_网约,
        "网约_f_次每天": round(f_网约, 1),
        "Robotaxi_进宁德_万辆": inc_robot,
        "Robotaxi_f_次每天": round(f_robot, 1),
        "乘用车_合计进宁德_万辆": inc_出租 + inc_网约 + inc_robot,
        "乘用车_站点级f_加权": round(f_taxi, 1),
        "续航_km": round(rng, 0),
        "电耗": e,
        "背电_kWh": cfg["背电_kWh"],
    }


def compute_private(cfg: dict):
    """私家车：累计保有净增法，三情景（保守/稳健/激进）。
    返回三档的进宁德车辆、站数、频次等；站数 = 日换电需求 ÷ 单站能力。
    """
    years = cfg["测算年限_年"]
    net_inc = cfg["私家车_2030_EV保有_万辆"] - cfg["私家车_2025_EV保有_万辆"]   # 8400万累计净增
    catl = cfg["CATL市占率"]
    battery = cfg["单车带电量_kWh"]
    f_day = cfg["换电频次_次每天"]
    single_station_cap = CONFIG_VAL["单站能力_次每天"]

    res = {"label": "私家车", "累计净增_万辆": net_inc, "CATL市占率": catl}
    for scenario in ("保守", "稳健", "激进"):
        pen = cfg["换电渗透率"][scenario]
        # 分档相乘后求和（每档独立渗透率）
        veh_total = 0
        for band, share in cfg["价格带分档占比"].items():
            band_veh = net_inc * share * pen[band]
            veh_total += band_veh
        veh_catl = veh_total * catl
        # 站数基于全市场换电车辆（站为所有换电车服务，不只CATL份额）；日需求=全市场车辆×f
        daily_swap = veh_total * f_day          # 万次/天
        stations = round(daily_swap * 1e4 / single_station_cap / 100) * 100   # 取整到百
        res[scenario] = {
            "全市场车辆_万": round(veh_total, 0),
            "宁德可及_万": round(veh_catl, 0),
            "日均换电_万次": round(daily_swap, 1),
            "需站数_座": stations,
        }
    return res


