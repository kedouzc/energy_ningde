def expand_vehicles(inc=None):
    """把只含根本参数的 vehicles 配置，逐年累加派生出每个场景的 ev_wan(累计) 与 ev_wan_2030(单年)。

    车型类型（三种，均只存最根本参数）：
      ① sales          : 逐年销量列表(万/年)，累计=Σsales，2030单年=sales[-1]（Robotaxi/私家车）
      ② stock/cycle+nev: 年销量=stock÷cycle，逐年电动化=年销量×nev[y]×pure_elec，
                         累计=Σ逐年，2030单年=年销量×nev[-1]×pure_elec（重卡/城配/出租/网约）
      ③ fixed          : 纯累计(旧兼容)，无单年口径
    每个场景填充：ev_wan(累计, 万) / ev_wan_2030(2030单年, 万)。
    返回深拷贝后的 vehicles，不污染原配置。
    """
    import copy
    P = inc or CONFIG_INC
    V = copy.deepcopy(P["vehicles"])
    # 出租/网约的 stock 由上游需求侧派生（根=运力需求，非直接给保有量）
    dm = derive_operating_demand(P)
    for vt, vd in V.items():
        if vd.get("from_demand"):
            vd["stock"] = dm[vt]
    YEARS = 5
    for vt, vd in V.items():
        pe = vd.get("pure_elec", 1.0)
        if "sales" in vd:
            # 逐年销量直接给：累计=Σ，单年=末年
            yearly = [s * pe for s in vd["sales"]]
            model_total = sum(yearly)
            model_2030 = yearly[-1]
        elif "fixed" in vd:
            # 旧兼容：纯累计，无单年（按均匀/5 占位单年，仅兜底）
            model_total = vd["fixed"] * pe
            model_2030 = model_total / YEARS
        else:
            # 年销量型：stock÷cycle=年销量，×逐年NEV×pure_elec
            annual = vd["stock"] / vd["cycle"]
            yearly = [annual * n * pe for n in vd["nev"]]
            model_total = sum(yearly)
            model_2030 = yearly[-1]
        for sc in vd["scenes"]:
            w = sc.get("weight", 1.0)
            sc["ev_wan"] = model_total * w
            sc["ev_wan_2030"] = model_2030 * w
    return V
    return V


def catl_swap_veh_wan(inc=None):
    """各车型宁德换电车辆数(万)：Σ场景 ev_wan × swap_rate × catl_swap。"""
    P = inc or CONFIG_INC
    V = expand_vehicles(P)
    out = {}
    for vt, vd in V.items():
        tot = 0.0
        for sc in vd["scenes"]:
            tot += sc["ev_wan"] * sc["swap_rate"] * sc["catl_swap"]
        out[vt] = tot
    return out


def compute_incremental_model(inc=None):
    """动力电池业务线 SOTP 估值（全口径：换电对【整个动力电池业务】的影响）。

    核心：2030 动力电池总市值 = 制造线 + 运营线 + 块3(全局定价权)。
      · 制造线（一次性销售，PE 法）：2030【单年】出货 × 2030价格 × 净利率 × PE
        出货口径 = 充电(全) + 换电×60%(外部经济权益；权益法未实现内部交易按持股比例抵消的简化口径)
      · 运营线（持续运营，EV/EBITDA 法）：2026-2030【累计】换电装机 → 正向EBITDA × 倍数 − 债 × 权益40%
      · 块3（全局定价权）：净利率差(有换电−无换电) × 制造线真实收入 × PE（全局受益，敏感性）
    装机是唯一地基：单年装机→制造线，累计装机→运营线，两个口径都从 config 逐年派生。
    """
    P = inc or CONFIG_INC
    V = expand_vehicles(P)

    # ---- 关键参数 ----
    OWN = P["platform_ownership"]          # 宁德对平台/电池归母权益 40%
    NM = P.get("mfg_net_margin", 0.11)    # 电池制造净利率 11%
    PE = P.get("pe_mfg", 20.0)            # 制造业务 PE 乘数
    EV_MULT = P.get("ev_ebitda", 18.0)    # 运营 EV/EBITDA 乘数
    price2030 = P["price_2030"]           # 2030 电池价格 544 元/kWh（折价后）
    ext = P["swap_external_share"]        # 换电电池外部股东占比 60%

    # ---- 装机漏斗（双口径：累计 + 2030单年）----
    # 累计口径（运营线）：换电 GWh
    cum_swap_gwh = 0.0
    cum_charge_gwh = 0.0
    # 单年口径（制造线）：换电/充电 GWh（2030 当年）
    y_swap_gwh = 0.0
    y_charge_gwh = 0.0

    rows = []
    for vtype, vd in V.items():
        kwh = vd["kwh"]
        for sc in vd["scenes"]:
            ev_wan = sc["ev_wan"]          # 累计
            ev_wan_2030 = sc["ev_wan_2030"]  # 单年
            sr = sc["swap_rate"]
            cs = sc["catl_swap"]
            cc = sc["catl_charge"]
            # 累计口径 GWh（宁德层）
            c_sw = ev_wan * 10000 * kwh / 1e6 * sr * cs
            c_ch = ev_wan * 10000 * kwh / 1e6 * (1 - sr) * cc
            # 单年口径 GWh（宁德层）
            y_sw = ev_wan_2030 * 10000 * kwh / 1e6 * sr * cs
            y_ch = ev_wan_2030 * 10000 * kwh / 1e6 * (1 - sr) * cc
            cum_swap_gwh += c_sw
            cum_charge_gwh += c_ch
            y_swap_gwh += y_sw
            y_charge_gwh += y_ch
            rows.append((vtype, sc["name"], ev_wan, ev_wan_2030, kwh, sr, cs, cc, c_sw, c_ch, y_sw, y_ch))

    # ---- 制造线（PE 法，2030 单年，用"有换电净利率"= 维持2026水平15%）----
    #   真实对外销售 = 充电(全) + 换电×60%(外部经济权益)；40%按权益法未实现内部交易抵消简化
    #   ★ 补"后续更换订单"（用户）：短寿命电池(城配/乘用营运3.8年)2026年装车、2030年到期重置，
    #     重置电池同样60%外部股东买单，对称于初装；2030年业务仍加速期，重置量小但口径需完整
    swap_life = P["swap_life"]                        # 电池寿命
    # 出租/网约/Robotaxi 归"乘用营运"寿命 3.8 年
    def _life(vt):
        if vt in ("出租", "网约", "Robotaxi"):
            return swap_life.get("乘用营运", 3.8)
        return swap_life.get(vt, 10.0)
    replace_gwh = 0.0                                 # 2030单年重置量(换电, 宁德口径)
    for vt, vd in V.items():
        life = _life(vt)
        if life > 4.0:                                # 寿命>4年, 2026装车2030未到期
            continue
        kwh = vd["kwh"]
        # 2026年电动化
        if "sales" in vd:
            y2026 = vd["sales"][0]
        elif "fixed" in vd:
            y2026 = vd["fixed"] / 5
        else:
            annual = vd["stock"] / vd["cycle"]
            y2026 = annual * vd["nev"][0] * vd.get("pure_elec", 1.0)
        # 2026年换电装机(宁德口径)
        for sc in vd["scenes"]:
            replace_gwh += y2026 * sc["weight"] * sc["swap_rate"] * sc["catl_swap"] * 10000 * kwh / 1e6
    replace_ext_gwh = replace_gwh * ext                # 制造线计入的重置量(60%外部股东)

    mfg_gwh = y_charge_gwh + y_swap_gwh * ext + replace_ext_gwh   # 制造线出货(新装+重置)
    mfg_rev = mfg_gwh * 1e6 * price2030 / 1e8        # 制造线收入(亿)
    nm_swap = P["nm_with_swap"]                      # 有换电净利率 15%（护价，维持2026水平）
    mfg_np = mfg_rev * nm_swap                       # 制造线净利(亿) = 收入×15%
    mfg_value = mfg_np * PE                          # 制造线市值(亿)

    # ---- 运营线（EV/EBITDA 法，累计换电装机，主表 §3.2 完整逻辑）----
    #   复用 fwd_segment（正向收入成本法）：服务费+装车租金+套利+辅助 − OPEX = EBITDA
    #   ★ 补漏项（用户）：站内周转电池 60% 外部股东出资 → 应收租金（与车主租金同价 120元/kWh·年）
    #     主表 §3.2 租金只计"装车GWh"，漏算站内周转电池的外部股东租金
    fwd = build_forward_table()
    seg_operating = fwd["营运"]                    # 营运车(重卡+城配+乘用) EBITDA
    seg_private = fwd["私营三档"]["稳健"]          # 稳健档(营运+私家稳健) EBITDA
    op_ebitda = seg_private["ebitda"]              # 稳健口径可交付 EBITDA = 779 亿

    # 站内周转电池外部股东租金（补漏项）
    #   站内周转电池合计 = 重卡12 + 乘用6 = 18 GWh；60% 外部股东 × 120元/kWh·年
    station_gwh = sum(s["站内GWh"] for s in FWD_SEG.values())   # 18 GWh
    station_ext_rent = station_gwh * 1e6 * ext * P["rent_rmb_kwh_year"] / 1e8  # 亿/年
    op_ebitda_adj = op_ebitda + station_ext_rent  # 修正后 EBITDA

    debt = P["lifecycle_capex_yi"] * P["debt_ratio"]  # 全周期债务 2409 亿
    # 基准18×回到Part 3披露锚4,829亿；倍数变化仍按EBITDA×权益的边际弹性展开。
    # 这样既保留底层未取整计算，又避免Part 5/6在16,608与16,618之间来回跳。
    op_value = P.get("op_value_anchor_yi", (op_ebitda_adj * EV_MULT - debt) * OWN)
    if "op_value_anchor_yi" in P:
        op_value += (EV_MULT - 18.0) * op_ebitda_adj * OWN

    # ---- 块3（全局定价权，单列用于"换电增量价值"，已含在制造线15%内不重复加）----
    #   块3 = 制造线(有换电15%) − 制造线(无换电12.5%) = 净利率差2.5% × 收入 × PE
    #   它已体现在"制造线用15%"里，单独拎出是为了算"换电贡献了多少定价权保护"
    nm_diff = P["nm_with_swap"] - P["nm_no_swap"]
    block3 = nm_diff * mfg_rev * PE                  # 全局定价权市值(亿)

    # ---- 总市值（SOTP）= 制造线(含护价) + 运营线 ----
    total_value = mfg_value + op_value

    return {
        "OWN": OWN, "NM": NM, "PE": PE, "EV_MULT": EV_MULT,
        "price2030": price2030, "ext": ext,
        # 装机地基（双口径）
        "cum_swap_gwh": cum_swap_gwh, "cum_charge_gwh": cum_charge_gwh,
        "y_swap_gwh": y_swap_gwh, "y_charge_gwh": y_charge_gwh,
        "replace_gwh": replace_gwh, "replace_ext_gwh": replace_ext_gwh,
        "mfg_gwh": mfg_gwh,
        # 制造线（含护价15%）
        "mfg_rev": mfg_rev, "mfg_np": mfg_np, "mfg_value": mfg_value,
        "nm_swap": nm_swap,
        # 运营线
        "op_ebitda": op_ebitda, "station_gwh": station_gwh,
        "station_ext_rent": station_ext_rent, "op_ebitda_adj": op_ebitda_adj,
        "debt": debt, "op_value": op_value,
        "seg_operating": seg_operating, "seg_private": seg_private,
        # 块3
        "nm_diff": nm_diff, "block3": block3,
        # 汇总
        "total_value": total_value,
        "rows": rows,
    }


def compute_power_diagnosis(inc=None, pe_base=20.0):
    """2026 vs 2030 动力电池业务线对比诊断（SOTP 全口径）。

    输出：
      2026 基准：收入/净利/装机/市值（实际数据推算）
      2030 SOTP：制造线(单年装机) + 运营线(累计装机) + 块3(全局定价权)
      对比：各主要业绩指标 2026→2030 的变化
    """
    P = inc or CONFIG_INC
    r = compute_incremental_model(P)
    pnl26 = derive_2026_pb_pnl(P)

    # 2026 基准（出货口径 = 装机×价格，与2030制造线同口径）
    rev2026 = pnl26["rev"]           # 3800 亿（644GWh × 590元）
    np2026 = pnl26["net"]            # 570 亿
    nm2026 = pnl26["nm"]             # 15%
    m2026 = np2026 * pe_base         # 11400 亿
    gwh2026 = pnl26["gwh"]           # 644 GWh
    price2026 = pnl26["price"]       # 590 元/kWh

    # 2030 SOTP
    mfg_rev = r["mfg_rev"]           # 制造线收入 3883
    mfg_np = r["mfg_np"]             # 制造线净利 485
    mfg_value = r["mfg_value"]
    op_ebitda = r["op_ebitda_adj"]   # 运营线 EBITDA(修正后)
    op_value = r["op_value"]
    block3 = r["block3"]
    total_value = r["total_value"]
    # 2030 收入拆解
    charge_rev = r["y_charge_gwh"] * 1e6 * r["price2030"] / 1e8   # 充电收入(全)
    swap_rev_ext = r["y_swap_gwh"] * r["ext"] * 1e6 * r["price2030"] / 1e8  # 换电×60%收入

    return {
        "pnl26": pnl26, "pe_base": pe_base,
        "rev2026": rev2026, "np2026": np2026, "nm2026": nm2026,
        "gwh2026": gwh2026, "price2026": price2026, "m2026": m2026,
        "mfg_rev": mfg_rev, "mfg_np": mfg_np, "mfg_value": mfg_value,
        "charge_rev": charge_rev, "swap_rev_ext": swap_rev_ext,
        "op_ebitda": op_ebitda, "op_value": op_value, "block3": block3,
        "total_value": total_value,
        "r": r,
        # 变化
        "d_market_cap": total_value - m2026,
        "d_gwh": r["mfg_gwh"] - gwh2026,
        "d_rev": mfg_rev - rev2026,
        "d_np": mfg_np - np2026,
        "nm_no_swap": P["nm_no_swap"], "nm_with_swap": P["nm_with_swap"],
    }


