def sensitivity_power(inc=None):
    """SOTP 总敏感性：量化高影响力参数对 2030 总市值的弹性。

    维度：
      ① 制造净利率 mfg_net_margin（→ 制造线净利 → 市值）
      ② 制造 PE pe_mfg（→ 制造线 + 块3 市值）
      ③ 运营 EV/EBITDA ev_ebitda（→ 运营线市值）
      ④ 净利率差 nm_with_swap−nm_no_swap（→ 块3，全局定价权）
      ⑤ 2030 电池价格 price_2030（→ 制造线收入）
    返回 rows：每组(参数组,情景,2030总市值,较基准变动)
    """
    P = (inc or CONFIG_INC).copy()
    base = compute_power_diagnosis(P)
    base_total = base["total_value"]
    rows = []

    def rec(grp, tag, P2=None):
        P2 = P2 or P
        d = compute_power_diagnosis(P2)
        rows.append((grp, tag, d["total_value"], d["total_value"] - base_total))

    # ① 制造净利率（无换电基准，围绕 12.5%）
    for nm in (0.10, 0.125, 0.15):
        P2 = dict(P); P2["mfg_net_margin"] = nm
        rec("①制造净利率(基准)", f"NM={nm:.1%}", P2)
    # ② 制造 PE
    for pe in (15, 20, 25):
        P2 = dict(P); P2["pe_mfg"] = pe
        rec("②制造PE", f"PE={pe}", P2)
    # ③ 运营 EV/EBITDA
    for ev in (15, 18, 22):
        P2 = dict(P); P2["ev_ebitda"] = ev
        rec("③运营EV/EBITDA", f"EV={ev}", P2)
    # ④ 净利率差（块3 全局定价权，围绕 2.5%：有换电15% vs 无换电12.5%）
    for diff in (0.01, 0.025, 0.04):
        P2 = dict(P); P2["nm_with_swap"] = P["nm_no_swap"] + diff
        rec("④净利率差(块3)", f"{diff:.1%}", P2)
    # ⑤ 2030 价格
    for price in (500, 544, 590):
        P2 = dict(P); P2["price_2030"] = price
        rec("⑤2030价格", f"{price}元", P2)
    return rows, base_total


def print_sensitivity_power(res=None):
    res = res or sensitivity_power()
    rows, base_total = res
    print("\n" + "=" * 70)
    print(f"【SOTP 总敏感性】基准 2030 总市值 = {base_total:.0f}亿 | 看各参数弹性")
    print("=" * 70)
    print(f"  {'参数组':<16}{'情景':<14}{'2030总市值':>13}{'较基准变动':>12}")
    for grp, tag, tot, dv in rows:
        print(f"  {grp:<16}{tag:<14}{tot:>13.0f}{dv:>+12.0f}")
    print("=" * 70)


