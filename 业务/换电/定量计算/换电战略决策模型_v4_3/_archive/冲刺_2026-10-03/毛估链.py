def economics(t):
    n = network(t); s = station(t); days = IN["运营天数"]; ud = IN["设计每千瓦每天_度"]
    F, D = s["固定每千瓦"], s["折旧每千瓦"]
    dS = F / (n["干线每千瓦每天"] * days) - F / (ud * days)     # 站没跑满（或超过设计）时每度站成本的变化
    bt = IN["悲观电池加购置税"] if t == "悲观" else 1.0
    mc_raw = margin_contested(t)[1]
    m = {"接力": -cell_diff("接力", t) - dS, "争夺块": cont_margin(t) - dS, "多班倒": -cell_diff("多班倒", t)}
    dep_st = {"接力": D / (n["干线每千瓦每天"] * days), "争夺块": D / (n["干线每千瓦每天"] * days),
              "多班倒": D / (ud * days)}
    dep_bt = {"接力": IN["接力电池每度"] * bt, "争夺块": IN["争夺块电池每度"] * bt, "多班倒": IN["多班倒电池每度"] * bt}
    vol = {"接力": n["接力卖量"], "争夺块": n["争夺块卖量"], "多班倒": n["多班倒卖量"]}
    ebitda_kwh = {k: m[k] + dep_st[k] + dep_bt[k] for k in m}
    ebit = sum(vol[k] * m[k] for k in m)
    ebitda = sum(vol[k] * ebitda_kwh[k] for k in m)
    bat_rep = sum(vol[k] * dep_bt[k] for k in m)
    st_rep = sum(vol[k] * dep_st[k] for k in m)
    # 投资
    n_st = n["干线站数"] + n["短途站数"]
    st_capex = n_st * s["站投资"] / 1e4                                                       # 亿元（站体）
    inv_capex = n_st * IN["周转电池_万元"] * bt / 1e4                                           # 周转电池（放电池银行，研究者定）
    trucks = {"接力": vol["接力"] * 1e8 / (IN["接力车年用电_万度"] * 1e4),
              "争夺块": vol["争夺块"] * 1e8 / (IN["干线车平均年用电_万度"] * 1e4 * IN["争夺块便宜格过站"]),
              "多班倒": vol["多班倒"] * 1e8 / (IN["多班倒车年用电_万度"] * 1e4)}
    kwh = {"接力": IN["干线车电池_度"], "争夺块": IN["干线车电池_度"], "多班倒": IN["短途车电池_度"]}
    truck_capex = sum(trucks[k] * kwh[k] * IN["电池单价_元每度"] * bt for k in trucks) / 1e8
    gwh = (sum(trucks[k] * kwh[k] for k in trucks) + n_st * 24 * 171) / 1e6
    capital = st_capex + inv_capex + truck_capex
    return dict(n, 站=s, 站成本变化=dS, 每度利润=m, 争夺块六格平均=mc_raw, 站折旧每度=dep_st,
                电池折旧每度=dep_bt, 每度EBITDA=ebitda_kwh, EBIT=ebit, EBITDA=ebitda,
                电池更新=bat_rep, 站更新=st_rep, 站总数=n_st, 站投资合计=st_capex, 周转电池投资=inv_capex,
                短途EBIT=vol["多班倒"] * m["多班倒"], 短途EBITDA=vol["多班倒"] * ebitda_kwh["多班倒"],
                换电车=trucks, 车上电池投资=truck_capex, 投资合计=capital, 电池装机GWh=gwh,
                税前资本回报=ebit / capital)

