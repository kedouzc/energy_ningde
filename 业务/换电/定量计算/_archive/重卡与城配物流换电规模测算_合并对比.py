def fwd_segment(seg: dict, V: dict, key: str = ""):
    """单段正向计算：收入(服务费/租金/套利) + OPEX(充电/场租/人工运维) → EBITDA。"""
    交易量_亿度 = seg["车"] * 1e4 * seg["单车kWh"] * 0.8 * seg["f"] * DAYS / 1e8   # 车万→度→亿度/年
    服务费 = 交易量_亿度 * V["度电服务费_元"]
    # 电池租金（收租装机口径）：车主装车 + 站内存量块外部股东占用（60%）均须交租
    收租装机GWh = seg["装车GWh"] + seg["站内GWh"] * V["平台外部股东占比"]
    # 单位：GWh × 1e6 kWh/GWh × 元/kWh·年 ÷ 1e8 = 亿/年
    租金 = 收租装机GWh * 1e6 * V["度电租金_元每年"] / 1e8   # 亿/年
    # 峰谷套利：仅站内周转电池一次谷充（确定性），电量=站内GWh×天数×RTE
    套利 = seg["站内GWh"] * 1e6 * V["套利天数"] * V["峰谷差_元每度"] * V["RTE"] / 1e8  # 亿/年
    # 充电成本：仅多出的电量 = 总充电量 − 交易量；总充电量=交易量/RTE×1.02
    总充电量 = 交易量_亿度 / V["RTE"] * (1 + V["厂用电率"])
    净充电电量 = 总充电量 - 交易量_亿度
    充电成本 = 净充电电量 * V["谷电价_元每度"]
    场租 = seg["站"] * V["单站年租_万"] / 1e4   # 亿/年
    # 人工运维：年服务次数 = 交易量_亿度×1e8 ÷ 单次补电量(单车kWh×0.8) ；单次成本按车型
    单次补电 = seg["单车kWh"] * 0.8
    年次数_亿次 = 交易量_亿度 * 1e8 / 单次补电 / 1e8
    车型 = "重卡" if seg["单车kWh"] >= 500 else "乘用"
    人工运维 = 年次数_亿次 * V["人工运维_元每次"][车型]
    # 软件调度：私家车固定 3 亿；营运段在 (20−3)=17 亿内按站数分摊（城配无站→0）
    if seg.get("私家"):
        软件 = V["软件_私家固定_亿"]
    else:
        营运站合计 = FWD_SEG["重卡"]["站"] + FWD_SEG["乘用"]["站"]
        软件 = (V["软件_亿每年"] - V["软件_私家固定_亿"]) * (seg["站"] / 营运站合计) if seg["站"] else 0
    # ⑤a 容量补偿（固定收益，存在即挣）：站数×单站申报容量×容量补偿单价(元/kW·年) ÷1e8（不乘小时）
    容量补偿 = seg["站"] * V["申报容量_kW"][车型] * V["容量补偿_元每kW年"] / 1e8 if seg["站"] else 0
    # ⑤b 需求响应电量补偿（变动收益）：站数×单站申报容量×等效小时×电量价 ÷1e8
    需求响应 = seg["站"] * V["申报容量_kW"][车型] * V["需求响应等效小时_h"] * V["需求响应电量价_元每kWh"] / 1e8 if seg["站"] else 0
    # ⑥ 调频 VPP：站数×可申报容量×年利用小时×调频价 ÷1e8（与⑤b互斥取孰高）
    调频 = seg["站"] * V["调频可申报_kW"][车型] * V["调频年利用小时_h"] * V["调频价_元每kWh"] / 1e8 if seg["站"] else 0
    # 实际计入营收的辅助服务：容量补偿(固定) + max(需求响应⑤b, 调频⑥)
    #   —— 容量补偿与电量/调频不互斥（两部制）；需求响应与调频同属实际调用，取孰高
    辅助服务 = 容量补偿 + max(需求响应, 调频)
    营收 = 服务费 + 租金 + 套利 + 辅助服务
    opex = 充电成本 + 场租 + 人工运维 + 软件
    ebitda = 营收 - opex
    # 站体能力校验：单站日接待车次 = 日换电量 ÷ 站数 ÷ 单次补电量
    #   注意：乘用营运站承接城配(站数=0)+私家车(并入)需求，故乘用段的"单站日接待"
    #         应把城配+私家车(稳健档)换电量并入分母站数的负荷，否则会误算成低负荷。
    if key == "乘用":
        _共享交易量 = 交易量_亿度 \
            + FWD_SEG["城配"]["车"] * FWD_SEG["城配"]["单车kWh"] * 0.8 * FWD_SEG["城配"]["f"] * DAYS / 1e4 \
            + FWD_SEG["私家稳健"]["车"] * FWD_SEG["私家稳健"]["单车kWh"] * 0.8 * FWD_SEG["私家稳健"]["f"] * DAYS / 1e4
    else:
        _共享交易量 = 交易量_亿度
    单站日接待 = (_共享交易量 * 1e8 / DAYS / seg["站"] / 单次补电) if seg["站"] else 0
    return {
        "交易量_亿度": round(交易量_亿度, 0), "服务费": round(服务费, 0),
        "租金": round(租金, 0), "套利": round(套利, 0),
        "容量补偿": round(容量补偿, 2), "需求响应": round(需求响应, 2),
        "调频": round(调频, 2), "辅助服务": round(辅助服务, 2),
        "营收": round(营收, 0), "充电成本": round(充电成本, 0),
        "场租": round(场租, 0), "人工运维": round(人工运维, 0),
        "软件": round(软件, 1), "opex": round(opex, 0), "ebitda": round(ebitda, 0),
        "单站日接待": round(单站日接待, 0),
    }


def build_forward_table():
    V = CONFIG_FWD
    segs = {k: fwd_segment(s, V, k) for k, s in FWD_SEG.items()}
    # 单块电量、单站块数（用于块次与日周转次数）
    单块 = {"重卡": 171, "城配": 80, "乘用": 56, "私家保守": 56, "私家稳健": 56, "私家激进": 56}
    站块数 = {"重卡": 24, "城配": 0, "乘用": 14, "私家保守": 14, "私家稳健": 14, "私家激进": 14}
    for k, s in FWD_SEG.items():
        seg = segs[k]
        # 【口径澄清】交易量已含余电折扣 0.8，即"净交付电量"。
        #   一块电池换出去时是满的(单块电量)，司机剩 20% 回来 → 单次净交付 = 单块×0.8。
        #   故分子分母必须同为"净交付"口径：
        #     日块次 = 日净交付电量 ÷ (单块×0.8)
        #     单块日周转次数 = 日块次 ÷ 站内周转块数
        #   原式用满块 171 作分母（分子却是净量），低估约 20%，已修正。
        #   注意：块次与"每车换几块"无关；每车块数只改变"车次"，不改变块次与周转次数。
        # 乘用营运与城配共用巧克力站(城配站数=0)，其"单站日接待"已把城配换电量并入，
        # 故此处日块次/翻台也须含城配，口径才自洽（否则会出现 179车次 vs 78块次 的错位）。
        if k == "乘用":
            共享交易量_亿度 = seg["交易量_亿度"] \
                + FWD_SEG["城配"]["车"] * 1e4 * FWD_SEG["城配"]["单车kWh"] * 0.8 * FWD_SEG["城配"]["f"] * DAYS / 1e8 \
                + FWD_SEG["私家稳健"]["车"] * 1e4 * FWD_SEG["私家稳健"]["单车kWh"] * 0.8 * FWD_SEG["私家稳健"]["f"] * DAYS / 1e8
        else:
            共享交易量_亿度 = seg["交易量_亿度"]
        日换电量_度 = 共享交易量_亿度 * 1e8 / DAYS
        单块净交付 = 单块[k] * 0.8
        日块次_全网 = 日换电量_度 / 单块净交付 if 单块净交付 else 0
        seg["单站日块次"] = round(日块次_全网 / s["站"], 0) if s["站"] else 0
        周转块数_全网 = s["站"] * 站块数[k]
        seg["日周转次数"] = round(日块次_全网 / 周转块数_全网, 1) if 周转块数_全网 else 0
        # 每车块数（隐含）= 单次补电量 ÷ 单块净交付；重卡 ≈ 2.9 块（500×0.8÷136.8）
        seg["每车块数"] = round(s["单车kWh"] * 0.8 / 单块净交付, 2) if 单块净交付 else 0

    def sc_agg(keys):
        agg = {}
        _small = {"容量补偿", "需求响应", "调频", "辅助服务"}  # 小数字，保留2位避免舍成0
        for k in ("交易量_亿度", "服务费", "租金", "套利", "容量补偿", "需求响应", "调频", "辅助服务",
                  "营收", "充电成本", "场租", "人工运维", "软件", "opex", "ebitda"):
            agg[k] = round(sum(segs[x][k] for x in keys), 2 if k in _small else 0)
        return agg

    营运 = sc_agg(["重卡", "城配", "乘用"])
    私营三档 = {sc: sc_agg(["重卡", "城配", "乘用", f"私家{sc}"]) for sc in ("保守", "稳健", "激进")}
    return {"各段": segs, "营运": 营运, "私营三档": 私营三档}


