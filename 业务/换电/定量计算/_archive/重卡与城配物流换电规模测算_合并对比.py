def build_group_resource_envelope(build=None, cfg=None):
    """不虚构其他战略预算，只算扣除分红/回购/换电后还能为其他战略留下的累计资金上限。"""
    C = cfg or CONFIG_BUILD_PHASE
    build = build or build_build_phase_cashflow(cfg=C)
    cash = C["集团期初现金_亿"]
    rows = []
    by_year = {r["年份"]: r for r in build["年度"]}
    for year in C["年份"]:
        begin = cash
        cfo = C["集团CFO_亿"][year]
        dividend = C["集团分红_亿"][year]
        buyback = C["集团回购_亿"][year]
        swap = by_year[year]["CATL净现金耗用"]
        cash = begin + cfo - dividend - buyback - swap
        after_shareholder_return = cfo - dividend - buyback
        rows.append({
            "年份": year, "期初现金": begin, "CFO": cfo, "分红": dividend, "回购": buyback,
            "换电净耗资": swap, "分红回购后当年增量资金": after_shareholder_return,
            "换电占CFO": swap / cfo if cfo else 0.0,
            "换电占分红回购后资金": swap / after_shareholder_return if after_shareholder_return > 0 else float("inf"),
            "未计其他战略投入前期末现金": cash,
            "其他战略累计可用上限": {floor: max(0.0, cash - floor)
                                    for floor in C["战略流动性底线情景_亿"]},
        })
    return {"年度": rows, "口径": "未计其他战略投入前的反向容量上限，不是现金预测"}


def _irr(cashflows):
    """年度等间距现金流IRR；无变号时返回None。"""
    if not (any(x < 0 for x in cashflows) and any(x > 0 for x in cashflows)):
        return None
    lo, hi = -0.99, 10.0
    def npv(rate):
        return sum(cf / ((1 + rate) ** i) for i, cf in enumerate(cashflows))
    while npv(hi) > 0 and hi < 1e6:
        hi *= 2
    for _ in range(200):
        mid = (lo + hi) / 2
        if npv(mid) > 0:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def build_post_stable_exit_table(exit_year=2033, build=None, cfg=None):
    """成熟后才比较10%—40%：过去投入是沉没资本，释放的是出售现金与未来更新义务。"""
    C = cfg or CONFIG_MATURE_EXIT
    if exit_year < C["最早出表年"]:
        raise ValueError(f"{exit_year}早于稳定经营门槛允许的最早出表年{C['最早出表年']}")
    build = build or build_build_phase_cashflow()
    inc = compute_incremental_model()
    current = C["建设期权益"]
    debt = C["项目债务_亿"]
    gross_ebitda = inc["op_ebitda_adj"]
    base_asset_ev = C["基准运营线价值_40_亿"] / current + debt
    base_swap_support = C["基准运营线价值_40_亿"] + C["基准护价价值_亿"]
    future_project_capex = CONFIG_BUILD_PHASE["全周期CAPEX现值_亿"] - CONFIG_BUILD_PHASE["初装CAPEX锚_亿"]
    base_catl_future_capital = future_project_capex * CONFIG_BUILD_PHASE["项目股权资本比例"] * current
    control_ok = all([C["数据场景控制权_硬约束"], C["标准与协议控制权_硬约束"], C["研发验证权_硬约束"]])
    scenarios = []

    for ownership in C["成熟期权益档"]:
        asset_light = ownership < current
        if asset_light:
            asset_ev = base_asset_ev / (1 + C["管理费率_EV"] * C["运营EV_EBITDA倍数"])
            management_fee = asset_ev * C["管理费率_EV"]
            manager_np = management_fee * C["管理平台利润率"] * (1 - C["管理平台税率"])
            manager_value = manager_np * C["管理平台PE"]
        else:
            asset_ev = base_asset_ev
            management_fee = manager_np = manager_value = 0.0
        equity_value = max(0.0, asset_ev - debt)
        sold = current - ownership
        sale_proceeds = equity_value * sold
        retained_operating_value = equity_value * ownership
        project_cash_after_fee = max(0.0, C["全项目年可分现金_亿"] - management_fee * (1 - C["管理平台税率"]))
        recurring_cash = project_cash_after_fee * ownership + manager_np
        retained_support = C["基准护价价值_亿"] + retained_operating_value + manager_value
        value_retention = retained_support / base_swap_support
        future_capital = future_project_capex * CONFIG_BUILD_PHASE["项目股权资本比例"] * ownership
        future_capital_released = base_catl_future_capital - future_capital

        # CATL现金IRR：2026—2030实际资本调用；稳定期退出前按40%收现金；退出后按终局经常性现金。
        yearly_calls = {r["年份"]: r["CATL净现金耗用"] for r in build["年度"]}
        cashflows = []
        for year in range(2026, 2041):
            cf = -yearly_calls.get(year, 0.0)
            if 2031 <= year < exit_year:
                cf += C["全项目年可分现金_亿"] * current
            elif year == exit_year:
                cf += sale_proceeds + recurring_cash
            elif year > exit_year:
                cf += recurring_cash
            cashflows.append(cf)

        ext = 1 - ownership
        mfg_gwh = inc["y_charge_gwh"] + (inc["y_swap_gwh"] + inc["replace_gwh"]) * ext
        mfg_rev = mfg_gwh * 1e6 * inc["price2030"] / 1e8
        raw_mfg_value = mfg_rev * inc["nm_swap"] * inc["PE"]
        mfg_value = C["基准制造线价值_40_亿"] + (raw_mfg_value - inc["mfg_value"])
        group_sotp = mfg_value + retained_operating_value + manager_value
        scenarios.append({
            "退出年": exit_year, "终局权益": ownership,
            "标签": ("10%规则放宽前瞻档" if ownership == 0.10 else
                    "20%中度循环" if ownership == 0.20 else
                    "30%温和循环" if ownership == 0.30 else "40%不进一步出表"),
            "业务数据控制权": control_ok,
            "会计并表结论": "须由届时治理协议按会计准则判断；业务主导权不等于会计控制",
            "一次性出售回款": sale_proceeds,
            "未来资本义务": future_capital,
            "未来资本释放": future_capital_released,
            "年经常性现金": recurring_cash,
            "保留运营权益价值": retained_operating_value,
            "管理平台价值": manager_value,
            "护价价值": C["基准护价价值_亿"],
            "可持续换电价值支撑": retained_support,
            "换电价值保留率": value_retention,
            "集团SOTP": group_sotp,
            "CATL现金IRR_至2040": _irr(cashflows),
            "可覆盖战略资金桶": {bucket: sale_proceeds / bucket for bucket in C["战略资金桶_亿"]},
            "是否达到时间门槛": exit_year >= C["最早出表年"],
        })
    return {
        "退出年": exit_year, "稳定门槛": C["稳定门槛"], "场景": scenarios,
        "40%换电价值支撑": base_swap_support,
        "说明": "不预设20%最优；只有实际稳定门槛达标后，权益比例才与集团战略资金缺口联立决定。",
    }


