// -------- 回填价格手册 §3.2.1/§3.2.2 表格（md 表逐年值 = js 推演展示，AUTO-GEN） --------
// 目的：消除"md 表手填值 vs js 三阶段推演"双源矛盾，使 md 表也成为单一数据源的输出。
// 仅回填 Y1-Y15 的数值行；Y0 行（初始价，自变量）保留手填、不被覆盖。
function syncManualTable() {
  if (!fs.existsSync(MD)) { console.log('[skip] 价格手册不存在'); return; }
  let md = fs.readFileSync(MD, 'utf8');
  const f3 = function (x) { return Number(x.toFixed(3)); };
  const f1 = function (x) { return (x * 100).toFixed(1) + '%'; };

  function genRows(usePower) {
    let rows = '';
    for (var k = 0; k < 16; k++) {
      var star = (k === 0) ? '**' : (k === 4 || k === 7 || k === 9 || k === 10) ? '**' : (k === 5 || k === 15) ? (k === 15 ? '**' : '**') : '';
      var yrMark = (k === 0 ? '**Y0**' : k === 5 ? '**Y5⭐**' : k === 15 ? '**Y15🔄**' : k === 4 ? '**Y4**' : k === 7 ? '**Y7⭐**' : k === 9 ? '**Y9⭐**' : k === 10 ? '**Y10⭐**' : 'Y' + k);
      var cell = usePower ? D.powerCell[k] : D.essCell[k];
      var packInt = usePower ? D.powerPackInt[k] : D.essPackInt[k];
      var bare = usePower ? D.powerBare[k] : D.essBare[k];
      var tax = usePower ? D.powerTax[k] : D.essTax[k];
      var block = usePower ? D.blockSettle[k] : Math.round(tax * 56 * 1000);
      var gm = usePower ? D.powerGm[k] : D.essGm[k];
      var sale = usePower ? D.powerSale[k] : D.essSale[k];
      rows += '| ' + yrMark + ' | **' + (2026 + k) + '** | **' + f3(cell) + '** | **' + f3(packInt) + '** | **' + f3(bare) + '** | **' + f3(tax) + '** | **' + block.toLocaleString('en-US') + '** | **' + f1(gm) + '** | **' + f3(sale) + '** |\n';
    }
    return rows;
  }

  function fillSection(mdText, anchor) {
    var reSec = new RegExp('(#### ' + anchor + '[\\s\\S]*?)(?=#### 3\\.2\\.[3-9]|#### 3\\.3|## )');
    var sec = mdText.match(reSec);
    if (!sec) return mdText;
    var secBody = sec[1];
    var usePower = anchor.indexOf('3.2.1') >= 0;
    var rows = genRows(usePower);
    // 替换表头之后的所有数据行（Y0..Y15）为生成行
    var reRows = /(\| 年份[^\n]*\n\|[-: |]*\n)[\s\S]*?(?=\n\n|\n>|\n####)/;
    if (!reRows.test(secBody)) return mdText;
    var newBody = secBody.replace(reRows, '$1' + rows);
    return mdText.replace(sec[1], newBody);
  }

  md = fillSection(md, '3.2.1');
  md = fillSection(md, '3.2.2');
  fs.writeFileSync(MD, md, 'utf8');
  console.log('[ok] 价格手册 §3.2.1/§3.2.2 表格已回填（js 三阶段推演值）');
}

// -------- 更新总表下游（(g)→⑤，随折扣链联动重算） --------
// 固定输入（车辆数×单车带电量×度电成本，与价格无关，不随价格变）
const TBL = {
  d: { 重卡: 1103, 城配: 247, 出租: 1068 },   // 电池初装 CAPEX（亿）
  e: { 重卡: 150, 城配: 150, 出租: 600 }        // 站体 CAPEX（亿）
};
function syncTotalTable() {
  if (!fs.existsSync(SWAP_DOC)) return;
  let doc = fs.readFileSync(SWAP_DOC, 'utf8');
  const WACC = 0.075;
  const capSec = 0.48;
  function netOf(years) {
    const buyNew = P.discountAt(D, years, 'power');
    const essDisc = P.discountAt(D, years, 'ess');
    return buyNew - essDisc * capSec; // 净重置 = 买新折 − 残值折
  }
  const endRes = P.discountAt(D, 15, 'ess') * (1 - 0.02 * 3.6) * 0.60;
  // 重卡全周期CAPEX倍数 = 1 + 第1次净重置×贴现 + 第2次净重置×贴现
  const capExMult = 1 + netOf(5.7) * Math.pow(1 - WACC, 5.7) + netOf(11.4) * Math.pow(1 - WACC, 11.4);
  const depBaseR = capExMult - endRes;
  const depCoefR = depBaseR / 5.7;
  // 城配全周期CAPEX倍数 = 1 + 4 次净重置×各自贴现
  const cityMult = 1 + netOf(3.8) * Math.pow(1 - WACC, 3.8) + netOf(7.6) * Math.pow(1 - WACC, 7.6) + netOf(11.4) * Math.pow(1 - WACC, 11.4) + netOf(15.2) * Math.pow(1 - WACC, 15.2);
  const depBaseC = cityMult - endRes;
  const depCoefC = depBaseC / 3.8;

  // 毛估拍放大倍数（与 §一/§三 一致）
  const gR = 1.4;                       // capExMult≈1.43 拍 1.4
  const gC = Math.round(cityMult * 10) / 10; // ≈1.8

  function col(name, dKey, gMul, depBase, depCoef) {
    const d = TBL.d[dKey], e = TBL.e[dKey];
    const h = Math.round(d * gMul + e);
    const endV = Math.round(d * endRes);
    const depBaseV = Math.round(d * depBase + e);
    const yrDep = Math.round(d * depCoef + e / 15);
    const depRate = yrDep / h;
    const ebRate = 0.20 - 0.333 * depRate;
    const ebitda = Math.round(h * ebRate);
    const ev = ebitda * 18;
    const debt = Math.round(h * 0.6);
    const eq = ev - debt;
    const ningde = Math.round(eq * 0.4);
    const fcff = Math.round(h * 0.15);
    return { h: h, endV: endV, depBaseV: depBaseV, yrDep: yrDep, depRate: depRate, ebRate: ebRate, ebitda: ebitda, ev: ev, debt: debt, eq: eq, ningde: ningde, fcff: fcff };
  }
  const R = col('重卡', '重卡', gR, depBaseR, depCoefR);
  const C = col('城配', '城配', gC, depBaseC, depCoefC);
  const Z = col('出租', '出租', gC, depBaseC, depCoefC);
  const sumH = R.h + C.h + Z.h, sumEnd = R.endV + C.endV + Z.endV, sumDep = R.depBaseV + C.depBaseV + Z.depBaseV;
  const sumYr = R.yrDep + C.yrDep + Z.yrDep, sumRate = sumYr / sumH, sumEb = 0.20 - 0.333 * sumRate;
  const sumEbV = Math.round(sumH * sumEb), sumEv = sumEbV * 18, sumDebt = Math.round(sumH * 0.6), sumEq = sumEv - sumDebt, sumNd = Math.round(sumEq * 0.4);
  const sumFcff = Math.round(sumH * 0.15);
  const pct2 = function (x) { return (x * 100).toFixed(1) + '%'; };
  const num = function (x) { return x.toLocaleString('en-US'); };

  const tail = [
    '| **(g)** | **EAC 放大倍数（仅电池）** | - | **×' + gR + '** | **×' + gC + '** | **×' + gC + '** | — |',
    '| **(h)** | **全周期 CAPEX 现值（亿）** | (d)×(g)+(e)（站体不重置） | **' + num(R.h) + '** | **' + num(C.h) + '** | **' + num(Z.h) + '** | **' + num(sumH) + '** |',
    '| — | CRF | 资本端视角期望收益率 10~15% | 0.150 | 0.150 | 0.150 | 0.150 |',
    '| **①** | **年 FCFF（亿，资本端要求锚）** | (h)×CRF（校验用，不参与②乘法） | **' + num(R.fcff) + '** | **' + num(C.fcff) + '** | **' + num(Z.fcff) + '** | **' + num(sumFcff) + '** |',
    '| — | 期末在役批残值（亿） | 见§一/§三：电池初装×' + endRes.toFixed(2) + ' | ' + num(R.endV) + ' | ' + num(C.endV) + ' | ' + num(Z.endV) + ' | ' + num(sumEnd) + ' |',
    '| — | 折旧基础总额（亿） | 电池初装×' + depBaseR.toFixed(2) + '/' + depBaseC.toFixed(2) + ' + 站体原值(e) | ' + num(R.depBaseV) + ' | ' + num(C.depBaseV) + ' | ' + num(Z.depBaseV) + ' | ' + num(sumDep) + ' |',
    '| — | 年折旧（亿） | 电池初装×' + depCoefR.toFixed(2) + '/' + depCoefC.toFixed(2) + ' + 站体(e)÷15 | ' + num(R.yrDep) + ' | ' + num(C.yrDep) + ' | ' + num(Z.yrDep) + ' | ' + num(sumYr) + ' |',
    '| — | 年折旧/(h) | 已含期末残值扣减 | ' + pct2(R.depRate) + ' | ' + pct2(C.depRate) + ' | ' + pct2(Z.depRate) + ' | ' + pct2(sumRate) + ' |',
    '| — | EBITDA/CAPEX = 0.20 − 0.333×折旧率 | 见§三（由折扣链折旧系数直接导出，不依赖①） | ' + R.ebRate.toFixed(3) + ' | ' + C.ebRate.toFixed(3) + ' | ' + Z.ebRate.toFixed(3) + ' | ' + sumEb.toFixed(3) + ' |',
    '| **②** | **年 EBITDA（亿）= (h)×EBITDA/CAPEX** | 由折扣链折旧系数直接导出；与(①−折旧×t)/(1−t)互验 | **' + num(R.ebitda) + '** | **' + num(C.ebitda) + '** | **' + num(Z.ebitda) + '** | **' + num(sumEbV) + '** |',
    '| — | EV/EBITDA 倍数（中枢 18×） | 给定 | 18 | 18 | 18 | 18 |',
    '| **③** | **整体 EV（亿）** | ②×EV/EBITDA | **' + num(R.ev) + '** | **' + num(C.ev) + '** | **' + num(Z.ev) + '** | **' + num(sumEv) + '** |',
    '| — | 债务（亿） | (h)×60%，资本结构股权40%+债60% | ' + num(R.debt) + ' | ' + num(C.debt) + ' | ' + num(Z.debt) + ' | ' + num(sumDebt) + ' |',
    '| **④** | **股权价值 Eq（亿）** | ③−债务 | **' + num(R.eq) + '** | **' + num(C.eq) + '** | **' + num(Z.eq) + '** | **' + num(sumEq) + '** |',
    '| — | CATL 权益比例（电池 40%） | - | 40% | 40% | 40% | 40% |',
    '| **⑤** | **宁德估值贡献（亿）** | ④×40% | **' + num(R.ningde) + '** | **' + num(C.ningde) + '** | **' + num(Z.ningde) + '** | **' + num(sumNd) + '** |'
  ].join('\n');

  doc = doc.replace(/\| \*\*\(g\)\*\*[\s\S]*?\| \*\*⑤\*\*[^\n]*\n/, tail + '\n');
  fs.writeFileSync(SWAP_DOC, doc, 'utf8');
  console.log('[ok] 总表下游已联动重算（重卡放大×' + gR + '、城配/出租×' + gC + '；宁德合计 ' + num(sumNd) + '亿）');
}

