/**
 * ============================================================
 * engine/userStructure.js — 用户结构推导算法（调和平均法）
 * ============================================================
 *
 * 核心问题：
 *   已知某换电站日均换电次数 X 次，问：服务了多少辆车？
 *   答：取决于营运车 vs 私家车的比例，因为两类车换电频率完全不同。
 *
 *
 * ── 算法推导 ──────────────────────────────────────
 *
 * 前提假设：
 *   营运车日均换电频率 f_c = 0.71 次/天（约每1.4天换一次）
 *   私家车日均换电频率 f_p = 0.20 次/天（约每5天换一次）
 *
 * 设：
 *   p  = 营运用户占比（0~1）
 *   U  = 总用户数（辆）
 *   X  = 日均换电次数
 *
 * 则两类用户的换电次数分别为：
 *   营运车换电 = U × p × f_c
 *   私家车换电 = U × (1-p) × f_p
 *
 * 总换电次数约束：
 *   X = U × p × f_c + U × (1-p) × f_p
 *     = U × [p × f_c + (1-p) × f_p]
 *
 * 解出总用户数：
 *   U = X / [p × f_c + (1-p) × f_p]
 *
 * 分母 [p × f_c + (1-p) × f_p] 就是"每用户日均换电次数的加权平均"。
 * 这个加权平均不是简单算术平均，而是**调和平均**的倒数形式。
 *
 * 调和平均换电频率 f = 1 / (p/f_c + (1-p)/f_p)
 * 则 U = X / f = X × [p/f_c + (1-p)/f_p]
 *
 * 两种形式数学等价，本模型使用调和平均形式。
 *
 *
 * ── 营运占比 p 如何确定 ─────────────────────────────
 *
 * p 随 X 变化：
 *   满载（X=125）时：营运占80%，私家占20%
 *   空载（X→0）时：营运占100%，私家接近0%
 *
 * 线性插值公式：
 *   p = 0.80 + 0.20 × (1 - X/125)
 *     = 1.00 - 0.20 × (X/125)
 *
 * 直觉：换电站刚建好时，周边还没形成用户习惯 → 只有死忠营运车来换电；
 *       随着运营成熟，私家车用户逐渐覆盖 → 营运占比下降至80%。
 *
 *
 * ── 为什么要用调和平均，不能用简单平均？ ──────────────
 *
 * 换电频率差异极大（0.71 vs 0.20，差3.5倍），简单算术平均会错误估计。
 *
 * 举例：X=100次/天，p=0.80
 *   调和平均：f = 1/(0.80/0.71 + 0.20/0.20) = 1/(1.127 + 1.000) = 0.470
 *            U = 100/0.470 ≈ 213辆
 *   算术平均：f = 0.80×0.71 + 0.20×0.20 = 0.568 + 0.040 = 0.608
 *            U = 100/0.608 ≈ 164辆
 *   差异：213 vs 164，差30%！调和平均正确，因为它正确处理了不同用户的"贡献权重"。
 *
 *
 * ── 原逻辑 vs model实现 ──────────────────────────
 *
 * MD文档原逻辑（#L1175-1210）：
 *   - 使用相同的调和平均公式
 *   - 与 model.html 实现完全一致
 *   - 结论：原逻辑正确，model实现也正确
 *
 * ------------------------------------------------------------
 * 加载顺序：在 constants.js 之后
 * 对应MD文档：宁德时代_超换一体站_财务模型_修正版.md # 5.1 用户结构推导
 * ============================================================
 */
var Engine = window.Engine || {};

/**
 * 计算用户结构（调和平均法）
 *
 * @param {number} X    - 日均换电次数（如 115）
 * @param {number} maxX - 满载换电次数（默认 125，24h模式为140）
 * @returns {{p:number, f:number, U:number, comm:number, priv:number}}
 *   p    - 营运用户占比（0~1）
 *   f    - 调和平均换电频率（次/天/辆）
 *   U    - 总用户数（辆）
 *   comm - 营运用户数（辆）
 *   priv - 私家车用户数（辆）
 *
 * 示例：
 *   X=115, maxX=125 → p=0.816, f=0.478, U≈241, comm≈197, priv≈44
 *   X=80,  maxX=125 → p=0.872, f=0.513, U≈156, comm≈136, priv≈20
 */
Engine.calcUserStructure = function (X, maxX) {
  var maxSwaps = maxX || 125;

  // 步骤1：计算营运用户占比（线性插值）
  //   满载(125次): p = 0.80
  //   空载(0次):   p = 1.00
  //   通用公式:    p = 0.80 + 0.20 × (1 - X/125)
  var p = Engine.COMM_RATIO_FULL_LOAD + (1 - Engine.COMM_RATIO_FULL_LOAD) * (1 - X / maxSwaps);

  // 步骤2：调和平均换电频率
  //   1/f = p / f_comm + (1-p) / f_priv
  //   推导：加权平均换电频率的倒数 = 各用户类型换电频率倒数的加权平均
  var f = 1 / (p / Engine.COMM_SWAP_FREQ + (1 - p) / Engine.PRIV_SWAP_FREQ);

  // 步骤3：总用户数
  //   U = X / f = X × (p/f_comm + (1-p)/f_priv)
  //   即：日均100次换电 ÷ 每用户平均0.47次/天 ≈ 213辆车
  var U = Math.round(X / f);

  // 步骤4：按占比分配营运/私家车数量
  var comm = Math.round(U * p);    // 营运用户数
  var priv = U - comm;             // 私家车用户数（用减法确保总数一致）

  return { p: p, f: f, U: U, comm: comm, priv: priv };
};