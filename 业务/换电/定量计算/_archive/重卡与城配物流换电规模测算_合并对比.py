def derive_operating_demand(inc=None):
    """乘用营运车上游需求侧派生（严格还原 v2.4③ 完整链条，根=运力需求）。

    步骤（每步均为显式中间量，不跳过）：
        T0        = 客运量 × 单次运距                         (亿车·km)
        robot_km  = Robotaxi保有 × 日均里程 × 年运营天 / 1e4  (亿车·km)
        N_有人     = (里程池2030 − robot_km) ÷ (日均里程 × 年运营天 / 1e4)  (万活跃有人车)
        online    = N_有人 − 出租刚性锚                       (网约总保有, 残差)
    返回 dict: {"出租": 出租总保有(刚性锚), "网约": online总保有}
    """
    import copy
    P = inc or CONFIG_INC
    d = P["operating_demand"]
    T0 = d["passenger_2025_yi"] * d["trip_km"]
    robot_km = d["robotaxi_fleet_wan"] * d["robotaxi_daily_km"] * d["robotaxi_days"] / 1e4
    N_有人 = (d["pool_2030_yi_km"] - robot_km) / (d["daily_km"] * d["days"] / 1e4)
    online = N_有人 - d["taxi_stock_wan"]
    return {"出租": d["taxi_stock_wan"], "网约": online,
            "_trace": {"T0": T0, "robot_km": robot_km, "N_有人": N_有人, "online": online}}


def derive_2026_pb_pnl(inc=None):
    """从实际分部数据【加权反推】2026 动力电池净利率（精确，不用毛利率−损耗率的粗略拍法）。

    核心约束：集团归母净利率 15.63% = 动力净利率×69.4% + 储能净利率×19.2% + 其他×11.4%
      · 储能净利率上限 ≈ 储能毛利率23.96% − 损耗 ≈ 17-18%（to B大客户，费用率相对低）
      · "其他"（含投资收益/政府补助/技术授权）净利率较高 ≈ 15-20%
      反推：动力净利率 ≈ 15%（远高于"毛利率−损耗率"误得的12.3%，因为集团净利率含非经营项目）
    关键认知（用户点破）：
      动力收入占比69.4%是绝对大头，动力净利率每低1pct，储能+其他要高出数倍才能维持集团15.63%，
      故动力净利率不能低——应≈15%，略低于集团(储能更高拉高集团)。
    推算链：
      收入2026 = 3165 × (1+46.02%) = 4621亿
      毛利率2026 = 20.63%（H1实际）
      动力真实损耗(费用+税) ≈ 5.6pct（非集团的8.3pct，集团8.3pct含投资收益稀释）
      净利率 = 20.63% − 5.6% ≈ 15%
      净利 = 4621 × 15% ≈ 695亿
    """
    P = inc or CONFIG_INC
    rev_fin = P["pb_2025_rev_yi"] * (1 + P["pb_2026_yoy"])  # 2026全年动力电池系统收入(财务口径) 4621亿
    gm = P["pb_2026h1_gm"]                                   # 2026动力毛利率 20.63%
    # 加权反推：动力净利率 ≈ 15%（储能≈17-18%、其他≈15-20% 加权后集团=15.63%）
    nm = P["pb_2026_nm"]                                     # 15%（加权反推锁定）
    # 出货口径收入 = 装机644GWh × 590元（与2030"装机×价格"同口径，便于对比）
    gwh2026 = P["gwh2026"]                                   # 644 GWh
    price2026 = P["battery_price"]                           # 590 元/kWh
    rev = gwh2026 * 1e6 * price2026 / 1e8                    # 出货口径收入 = 3800亿
    gross = rev * gm                                         # 毛利(出货口径)
    net = rev * nm                                           # 净利(出货口径) = 3800×15% = 570亿
    loss_rate = gm - nm                                      # 动力真实损耗率 ≈ 5.6%
    return {"rev": rev, "rev_fin": rev_fin, "gm": gm, "gross": gross,
            "loss_rate": loss_rate, "nm": nm, "net": net,
            "gwh": gwh2026, "price": price2026,
            "opex_equiv": gross - net}


